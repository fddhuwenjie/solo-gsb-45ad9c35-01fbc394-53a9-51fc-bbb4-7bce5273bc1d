# 标志层：标签, 说明, {孔名: 该孔中的层序序号(1 基)}
# ZK04 的 7、8 两层为高程对称的相同砂岩，默认参数下即构成并列最优歧义
MARKERS = [
    ("M1", "可采煤层（全区稳定）",
     {"ZK01": 6, "ZK02": 7, "ZK03": 6, "ZK04": 6}),
    ("L1", "灰岩标志层",
     {"ZK01": 8, "ZK02": 9, "ZK03": 8, "ZK04": 9}),
]


def seed_if_empty(conn):
    count = conn.execute("SELECT COUNT(*) c FROM borehole").fetchone()["c"]
    if count:
        return False
    hole_ids = {}
    for name, x, elev, note in BOREHOLES:
        cur = conn.execute(
            "INSERT INTO borehole (name, x, collar_elev, note) VALUES (?,?,?,?)",
            (name, x, elev, note),
        )
        hole_ids[name] = cur.lastrowid
    layer_id = {}   # (hole, seq) -> layer id
    for name, rows in LAYERS.items():
        for idx, (top, bottom, lith, grain, water, conf) in enumerate(rows, 1):
            cur = conn.execute(
                "INSERT INTO layer (borehole_id, seq, top, bottom, lithology,"
                " grain, water, confidence) VALUES (?,?,?,?,?,?,?,?)",
                (hole_ids[name], idx, top, bottom, lith, grain, water, conf),
            )
            layer_id[(name, idx)] = cur.lastrowid
    for label, desc, mapping in MARKERS:
        cur = conn.execute(
            "INSERT INTO marker (label, description) VALUES (?,?)",
            (label, desc),
        )
        mid = cur.lastrowid
        for name, seq in mapping.items():
            conn.execute(
                "INSERT INTO marker_layer (marker_id, borehole_id, layer_id)"
                " VALUES (?,?,?)",
                (mid, hole_ids[name], layer_id[(name, seq)]),
            )
    conn.commit()
    return True
